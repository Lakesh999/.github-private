{
    private readonly string _testWorkspace;
    private readonly LoopStateManager _stateManager;
    private readonly PlanPhaseParser _planPhaseParser;

    public ResearchLoopTests()
    {
        _testWorkspace = Path.Combine(
            Path.GetTempPath(), $"ResearchLoopTests_{Guid.NewGuid():N}");
        Directory.CreateDirectory(_testWorkspace);

        // Create docs subdirectories that EnsurePhaseOutputDirectoryExists expects
        Directory.CreateDirectory(Path.Combine(_testWorkspace, "docs", "vision"));
        Directory.CreateDirectory(Path.Combine(_testWorkspace, "docs", "research"));
        Directory.CreateDirectory(Path.Combine(_testWorkspace, "docs", "plans"));

        _stateManager = new LoopStateManager(_testWorkspace, Log.Logger);
        _planPhaseParser = new PlanPhaseParser();
    }

    public void Dispose()
    {
        if (Directory.Exists(_testWorkspace))
        {
            try { Directory.Delete(_testWorkspace, recursive: true); }
            catch { /* best-effort cleanup */ }
        }
    }

    #region Helper Methods

    private async Task<ResearchTestOrchestrator> CreateOrchestratorAsync(
        Func<LoopPhase, int, PhaseResult> resultProvider)
    {
        await _stateManager.CreateRunAsync("test research feature");

        var config = new HughConfig
        {
            AgentsPath = Path.Combine(_testWorkspace, "agents"),
            DocsPath = Path.Combine(_testWorkspace, "docs"),
            OrchestratorPath = Path.Combine(_testWorkspace, ".orchestrator"),
            Autonomous = new AutonomousConfig
            {
                Enabled = true,
                AcceptRecommendationsOnly = true,
                InteractivePhases = new List<string>()
            },
            Copilot = new CopilotConfig
            {
                MaxPhaseRetries = 0
            },
            Verification = new VerificationConfig
            {
                Enabled = false
            }
        };

        var options = Options.Create(config);
        var mockCopilot = Substitute.For<ICopilotService>();
        var mockRegistry = Substitute.For<IAgentRegistry>();
        var phaseExecutor = new PhaseExecutor(
            mockCopilot, mockRegistry, _stateManager,
            options, NullLogger<PhaseExecutor>.Instance, new CancellationTokenSource());

        return new ResearchTestOrchestrator(
            phaseExecutor,
            _stateManager,
            _planPhaseParser,
            options,
            NullLogger<LoopOrchestrator>.Instance,
            resultProvider);
    }

    /// <summary>
    /// Creates a LoopState starting at the specified phase with all prior phases marked complete.
    /// For document-producing phases that are complete, creates placeholder files on disk.
    /// </summary>
    private LoopState CreateStateAtPhase(LoopPhase startPhase)
    {
        var completedPhases = new List<LoopPhase>();
        var allPhases = new[]
        {
            LoopPhase.Vision, LoopPhase.Research, LoopPhase.Planning,
            LoopPhase.Review, LoopPhase.Coding
        };

        var documents = new DocumentPaths();

        foreach (var p in allPhases)
        {
            if (p == startPhase) break;
            completedPhases.Add(p);

            // Create placeholder documents for document-producing phases
            var docPath = p switch
            {
                LoopPhase.Vision => Path.Combine(_testWorkspace, "docs", "vision", "test-vision.md"),
                LoopPhase.Research => Path.Combine(_testWorkspace, "docs", "research", "test-research.md"),
                LoopPhase.Planning => Path.Combine(_testWorkspace, "docs", "plans", "test-plan.md"),
                _ => null
            };

            if (docPath != null)
            {
                Directory.CreateDirectory(Path.GetDirectoryName(docPath)!);
                File.WriteAllText(docPath, $"# Placeholder for {p}\n\nGenerated by test setup.");
                documents = p switch
                {
                    LoopPhase.Vision => documents with { Vision = docPath },
                    LoopPhase.Research => documents with { Research = docPath },
                    LoopPhase.Planning => documents with { Plan = docPath },
                    _ => documents
                };
            }
        }

        return new LoopState
        {
            RunId = Guid.NewGuid(),
            StartedAt = DateTime.UtcNow,
            FeatureRequest = "test research feature",
            CurrentPhase = startPhase,
            CompletedPhases = completedPhases,
            Documents = documents,
            Status = PhaseStatus.NotStarted
        };
    }

    #endregion

    #region Research Dispatch Routing Tests

    [Fact]
    public async Task ResearchPhase_DispatchRouting_ResearchIsDispatched()
    {
        // Arrange: Start at Research phase (Vision already complete).
        // The mock produces a research doc on disk so the document-exists check passes.
        var researchDocPath = Path.Combine(_testWorkspace, "docs", "research", "test-output.md");

        var orchestrator = await CreateOrchestratorAsync((phase, callNum) =>
        {
            if (phase == LoopPhase.Research)
            {
                // Create the research document on disk (simulates what the real executor would do)
                File.WriteAllText(researchDocPath, "# Research\n\nAll phases complete.");
                return new PhaseResult
                {
                    Success = true,
                    OutputDocumentPath = researchDocPath,
                    Duration = TimeSpan.FromSeconds(1)
                };
            }

            // All other phases succeed with placeholder docs
            var docPath = phase switch
            {
                LoopPhase.Planning => Path.Combine(_testWorkspace, "docs", "plans", "output-plan.md"),
                _ => null
            };

            if (docPath != null)
            {
                Directory.CreateDirectory(Path.GetDirectoryName(docPath)!);
                File.WriteAllText(docPath, $"# {phase} output");
            }

            return new PhaseResult
            {
                Success = true,
                OutputDocumentPath = docPath,
                Duration = TimeSpan.FromSeconds(1)
            };
        });

        var state = CreateStateAtPhase(LoopPhase.Research);

        // Act
        var result = await orchestrator.ExecuteLoopAsync(state, CancellationToken.None);

        // Assert: The loop completed successfully and Research was dispatched exactly once
        Assert.True(result);
        var researchCalls = orchestrator.DispatchCalls
            .Where(c => c.Phase == LoopPhase.Research)
            .ToList();
        Assert.Single(researchCalls);
    }

    [Fact]
    public async Task ResearchPhase_DispatchRouting_FailureStopsLoop()
    {
        // Arrange: Research fails — the loop should stop and return false.
        var orchestrator = await CreateOrchestratorAsync((phase, callNum) =>
        {
            if (phase == LoopPhase.Research)
            {
                return new PhaseResult
                {
                    Success = false,
                    ErrorMessage = "Research outline creation failed",
                    Duration = TimeSpan.FromSeconds(1)
                };
            }

            return new PhaseResult
            {
                Success = true,
                Duration = TimeSpan.FromSeconds(1)
            };
        });

        var state = CreateStateAtPhase(LoopPhase.Research);

        // Act
        var result = await orchestrator.ExecuteLoopAsync(state, CancellationToken.None);

        // Assert: Loop failed, only Research was attempted
        Assert.False(result);
        Assert.Single(orchestrator.DispatchCalls);
        Assert.Equal(LoopPhase.Research, orchestrator.DispatchCalls[0].Phase);
    }

    [Fact]
    public async Task ResearchPhase_DispatchRouting_SuccessProducesOutputDocument()
    {
        // Arrange: Research succeeds with an output document path.
        // Verify the orchestrator records the document path in state.
        var researchDocPath = Path.Combine(_testWorkspace, "docs", "research", "research-out.md");

        var orchestrator = await CreateOrchestratorAsync((phase, callNum) =>
        {
            if (phase == LoopPhase.Research)
            {
                File.WriteAllText(researchDocPath, "# Research output");
                return new PhaseResult
                {
                    Success = true,
                    OutputDocumentPath = researchDocPath,
                    Duration = TimeSpan.FromSeconds(1)
                };
            }

            var docPath = phase switch
            {
                LoopPhase.Planning => Path.Combine(_testWorkspace, "docs", "plans", "plan-out.md"),
                _ => null
            };

            if (docPath != null)
            {
                Directory.CreateDirectory(Path.GetDirectoryName(docPath)!);
                File.WriteAllText(docPath, $"# {phase} output");
            }

            return new PhaseResult
            {
                Success = true,
                OutputDocumentPath = docPath,
                Duration = TimeSpan.FromSeconds(1)
            };
        });

        var state = CreateStateAtPhase(LoopPhase.Research);

        // Act
        var result = await orchestrator.ExecuteLoopAsync(state, CancellationToken.None);

        // Assert: Research document was recorded in state after completion
        Assert.True(result);
        var finalState = _stateManager.CurrentState;
        Assert.NotNull(finalState);
        Assert.Equal(researchDocPath, finalState.Documents.Research);
    }

    [Fact]
    public async Task ResearchPhase_MissingOutputDocument_FailsLoop()
