    [Fact]
    public async Task FullPipeline_ResearchPhaseInSequence_DispatchesAllPhases()
    {
        // Arrange: Run from Vision through Coding. All phases succeed.
        // Verify Research is dispatched in the correct sequence position.
        var visionDocPath = Path.Combine(_testWorkspace, "docs", "vision", "vision-seq.md");
        var researchDocPath = Path.Combine(_testWorkspace, "docs", "research", "research-seq.md");
        var planDocPath = Path.Combine(_testWorkspace, "docs", "plans", "plan-seq.md");

        // Pre-create needed files
        File.WriteAllText(planDocPath, """
            # Test Plan

            ## Progress Summary

            | Phase | Description | Status | Tasks |
            |-------|-------------|--------|-------|
            | 1 | Setup | ✅ Complete | 1/1 |
            """);

        var orchestrator = await CreateOrchestratorAsync((phase, callNum) =>
        {
            var docPath = phase switch
            {
                LoopPhase.Vision => visionDocPath,
                LoopPhase.Research => researchDocPath,
                LoopPhase.Planning => planDocPath,
                _ => null
            };

            if (docPath != null)
            {
                Directory.CreateDirectory(Path.GetDirectoryName(docPath)!);
                File.WriteAllText(docPath, $"# {phase} output\n\nGenerated by test.");
            }

            return new PhaseResult
            {
                Success = true,
                OutputDocumentPath = docPath,
                Duration = TimeSpan.FromSeconds(1)
            };
        });

        var state = CreateStateAtPhase(LoopPhase.Vision);

        // Act
        var result = await orchestrator.ExecuteLoopAsync(state, CancellationToken.None);

        // Assert: All 5 phases dispatched in order
        Assert.True(result);
        Assert.Equal(5, orchestrator.DispatchCalls.Count);

        var dispatchedPhases = orchestrator.DispatchCalls.Select(c => c.Phase).ToList();
        Assert.Equal(LoopPhase.Vision, dispatchedPhases[0]);
        Assert.Equal(LoopPhase.Research, dispatchedPhases[1]);
        Assert.Equal(LoopPhase.Planning, dispatchedPhases[2]);
        Assert.Equal(LoopPhase.Review, dispatchedPhases[3]);
        Assert.Equal(LoopPhase.Coding, dispatchedPhases[4]);
    }

